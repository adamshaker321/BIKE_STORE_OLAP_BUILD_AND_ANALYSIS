USE SalesDW;
GO

SELECT
    ROW_NUMBER() OVER (ORDER BY O.ORDER_ID) AS SALES_KEY,
    O.ORDER_ID,
    DC.CUSTOMER_KEY,
    DSF.STAFF_KEY,
    DSR.STORE_KEY,
    DP.PRODUCT_KEY,
    ODD.DATE_KEY AS ORDER_DATE_KEY,
    RDD.DATE_KEY AS REQUIRED_DATE_KEY,
    SDD.DATE_KEY AS SHIPPED_DATE_KEY,
    OI.QUANTITY,
    OI.LIST_PRICE AS UNIT_PRICE,
    (OI.QUANTITY * OI.LIST_PRICE * (1 - OI.DISCOUNT)) AS SALES_AMOUNT,
    OI.DISCOUNT
INTO Gold.fact_sales
FROM Silver.orders AS O
JOIN Silver.order_items AS OI
    ON O.ORDER_ID = OI.ORDER_ID
JOIN Gold.dim_customers AS DC
    ON O.CUSTOMER_ID = DC.CUSTOMER_ID
JOIN Gold.dim_staffs AS DSF
    ON O.STAFF_ID = DSF.STAFF_ID
JOIN Gold.dim_stores AS DSR
    ON O.STORE_ID = DSR.STORE_ID
JOIN Gold.dim_products AS DP
    ON OI.PRODUCT_ID = DP.PRODUCT_ID
JOIN Gold.dim_date AS ODD
    ON O.ORDER_DATE = ODD.FULL_DATE
JOIN Gold.dim_date AS RDD
    ON O.REQUIRED_DATE = RDD.FULL_DATE
JOIN Gold.dim_date AS SDD
    ON O.SHIPPED_DATE = SDD.FULL_DATE;